spec = importlib.util.spec_from_file_location(
    "api_tester_server", Path(__file__).resolve().parents[3] / "serve-api-tester.py"
)
server = importlib.util.module_from_spec(spec)
spec.loader.exec_module(server)

class ByteStreamConnection:
    """Adapt byte streams to the handler's socket I/O boundary; opens no socket."""
    def __init__(self, request):
        self.input = io.BytesIO(request)
        self.output = io.BytesIO()

    def makefile(self, *_args):
        return self.input

    def sendall(self, data):
        self.output.write(data)

class TesterServerTest(unittest.TestCase):
    def request(self, path, method="GET"):
        connection = ByteStreamConnection(
            f"{method} {path} HTTP/1.0\r\nHost: localhost\r\n\r\n".encode()
        )
        server.TesterHandler(connection, ("127.0.0.1", 0),
                             SimpleNamespace(server_name="localhost", server_port=0))
        self.last_response = connection.output.getvalue()
        response = HTTPResponse(ByteStreamConnection(self.last_response), method=method)
        response.begin()
        return response

