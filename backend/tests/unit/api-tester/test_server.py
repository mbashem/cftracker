"""Exercise tester HTTP handlers with in-memory output and mocked file access."""
import importlib.util
import io
from pathlib import Path
import unittest
from unittest.mock import MagicMock, patch

spec = importlib.util.spec_from_file_location(
    "api_tester_server", Path(__file__).resolve().parents[3] / "serve-api-tester.py"
)
server = importlib.util.module_from_spec(spec)
spec.loader.exec_module(server)


class TesterServerTest(unittest.TestCase):
    def handler(self, path):
        handler = object.__new__(server.TesterHandler)
        handler.path = path
        handler.wfile = io.BytesIO()
        for name in ("send_response", "send_header", "end_headers", "send_error"):
            setattr(handler, name, MagicMock())
        return handler

    # Generated by Codex and not thoroughly checked for correctness.
    def test_environment_source_and_traversal_requests_never_access_files(self):
        with patch.object(server, "ROOT") as root:
            for path in ("/backend/.env", "/.env", "/backend/internal/auth/auth_handlers.go", "/backend/../.env", "/backend/%2e%2e/.env"):
                with self.subTest(path=path):
                    handler = self.handler(path)
                    handler.do_GET()
                    handler.send_error.assert_called_once_with(404)
            root.__truediv__.assert_not_called()

    # Generated by Codex and not thoroughly checked for correctness.
    def test_callback_queries_use_the_tester_asset_and_javascript_has_a_valid_mime_type(self):
        with patch.object(server, "ROOT") as root:
            root.__truediv__.return_value.read_bytes.return_value = b"mock asset"
            for path, filename, content_type in (
                ("/backend/api-tester.html?code=secret&state=state", "api-tester.html", "text/html; charset=utf-8"),
                ("/callback/auth-gh?code=secret&state=state", "api-tester.html", "text/html; charset=utf-8"),
                ("/backend/api-tester.mjs", "api-tester.mjs", "text/javascript; charset=utf-8"),
            ):
                with self.subTest(path=path):
                    root.reset_mock()
                    handler = self.handler(path)
                    handler.do_GET()
                    root.__truediv__.assert_called_once_with(filename)
                    handler.send_response.assert_called_once_with(200)
                    handler.send_header.assert_any_call("Content-Type", content_type)
                    handler.send_header.assert_any_call("Cache-Control", "no-store")
                    self.assertEqual(handler.wfile.getvalue(), b"mock asset")

    # Generated by Codex and not thoroughly checked for correctness.
    def test_head_has_headers_without_a_body_and_missing_assets_return_404(self):
        with patch.object(server, "ROOT") as root:
            root.__truediv__.return_value.read_bytes.return_value = b"mock asset"
            handler = self.handler("/backend/api-tester.html")
            handler.do_HEAD()
            handler.send_header.assert_any_call("Content-Length", "10")
            self.assertEqual(handler.wfile.getvalue(), b"")
            root.__truediv__.return_value.read_bytes.side_effect = OSError("mock missing asset")
            handler = self.handler("/backend/api-tester.html")
            handler.do_GET()
            handler.send_error.assert_called_once_with(404)
