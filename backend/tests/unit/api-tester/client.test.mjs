test("GitHub completion includes the state cookie and persists only the resulting session", async () => {
  const { client, respond, requests, values } = fixture();
  client.setToken("previous-session");
  await client.request("lists");
  requests.length = 0;
  const login = new URL(client.beginOAuth());
  assert.equal(login.origin + login.pathname, "http://localhost:8080/api/v1/auth/github/login");
  assert.equal(login.search, "");
  respond(async () => Response.json({ token: "github-session", user: { id: 7, github_username: "octocat" } }));
  await client.completeOAuth("code +&?", "state &?");
  const url = new URL(requests[0].url);
  assert.equal(url.searchParams.get("code"), "code +&?");
  assert.equal(url.searchParams.get("state"), "state &?");
  assert.equal(requests[0].credentials, "include");
  assert.equal(requests[0].headers.Authorization, undefined);
  assert.equal(client.snapshot().workspace.token, "github-session");
  assert.equal(client.snapshot().workspace.profile.github_username, "octocat");
  assert.equal(client.snapshot().pendingOAuth, undefined);
  assert.equal(client.snapshot().workspace.history.length, 1);
  assert.ok(!values.get(STORAGE_KEY).includes("code +&?"));
  assert.ok(!values.get(STORAGE_KEY).includes("state &?"));
});

