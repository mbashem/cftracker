import { test } from "node:test";
import assert from "node:assert/strict";
import { buildRequest, createTesterClient, ENDPOINTS, normalizeOrigin, STORAGE_KEY } from "../../../api-tester-client.mjs";

function fixture() {
  const values = new Map();
  const storage = {
    getItem: key => values.get(key) ?? null,
    setItem: (key, value) => values.set(key, value),
    removeItem: key => values.delete(key),
  };
  const requests = [];
  let respond = async () => Response.json({ status: "alive" });
  let time = 1800000000000;
  const options = {
    storage, now: () => time,
    fetch: async (url, init) => { requests.push({ url, ...init }); return respond(url, init); },
  };
  return {
    client: createTesterClient(options), options, requests, values,
    respond: handler => { respond = handler; }, advance: delta => { time += delta; },
  };
}

