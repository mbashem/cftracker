test("logout prevents delayed OAuth and private responses from restoring a session or history", async () => {
  for (const oauth of [false, true]) {
    const { client, respond } = fixture();
    client.setToken("old-session");
    let resolve;
    respond(() => new Promise(done => { resolve = done; }));
    if (oauth) client.beginOAuth();
    const pending = oauth ? client.completeOAuth("code", "state") : client.request("lists");
    client.logout();
    resolve(Response.json({ token: "late-session", lists: [{ name: "Private" }] }));
    assert.equal((await pending).stale, true);
    assert.equal(client.snapshot().workspace.token, "");
    assert.equal(client.snapshot().workspace.history.length, 0);
  }
});

