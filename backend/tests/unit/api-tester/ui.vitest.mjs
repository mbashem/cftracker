// Generated by Codex and not thoroughly checked for correctness.
test("clearing a session during a request prevents its late private response from appearing", async () => {
  await boot(); token("private-session"); select("profile");
  let resolve;
  fetchMock.mockImplementationOnce(() => new Promise(done => { resolve = done; }));
  submit("request-form");
  element("logout").click();
  resolve(Response.json({ user: { id: 7, github_username: "private-user" } }));
  await vi.waitFor(() => expect(element("send").textContent).not.toContain("Sending"));
  expect(element("response-body").textContent).toBe("No response yet.");
  expect(element("profile-summary").textContent).toBe("No saved session.");
  expect(element("token").value).toBe("");
  expect(element("send").disabled).toBe(true);
});

