import { afterEach, beforeEach, expect, test, vi } from "vitest";
import html from "../../../api-tester.html?raw";
import { STORAGE_KEY } from "../../../api-tester-client.mjs";

let fetchMock;
let eventSpy;
const element = id => document.getElementById(id);
const submit = id => element(id).dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
beforeEach(() => {
  vi.resetModules();
  vi.useFakeTimers();
  vi.setSystemTime(new Date("2026-10-26T12:00:00Z"));
  localStorage.clear();
  window.history.replaceState(null, "", "/backend/api-tester.html");
  document.documentElement.innerHTML = html;
  fetchMock = vi.fn(async () => Response.json({ status: "alive" }));
  vi.stubGlobal("fetch", fetchMock);
  eventSpy = vi.spyOn(window, "addEventListener");
});
afterEach(() => {
  for (const args of eventSpy.mock.calls) window.removeEventListener(...args);
  document.body.replaceChildren();
  localStorage.clear();
  vi.restoreAllMocks();
  vi.unstubAllGlobals();
  vi.useRealTimers();
});
async function boot() { await import("../../../api-tester.mjs"); }
function select(id) { element("endpoint").value = id; element("endpoint").dispatchEvent(new Event("change")); }
function token(value) { element("token").value = value; submit("token-form"); }

// Generated by Codex and not thoroughly checked for correctness.
test("startup stays offline, endpoint presets work, and token paste enables protected requests", async () => {
  await boot();
  expect(fetchMock).not.toHaveBeenCalled();
  expect(element("endpoint").options).toHaveLength(13);
  select("profile");
  expect(element("send").disabled).toBe(true);
  token("Bearer pasted-session");
  expect(element("send").disabled).toBe(false);
  fetchMock.mockResolvedValueOnce(Response.json({ user: { id: 7, github_username: "octocat" } }));
  submit("request-form");
  await vi.waitFor(() => expect(element("profile-summary").textContent).toContain("octocat"));
  expect(fetchMock.mock.calls[0][1].headers.Authorization).toBe("Bearer pasted-session");
  expect(JSON.parse(localStorage.getItem(STORAGE_KEY)).environments["http://localhost:8080"].token).toBe("pasted-session");
});

// Generated by Codex and not thoroughly checked for correctness.
test("request parameters and raw body are used and untrusted responses render only as text", async () => {
  await boot(); token("session"); select("add");
  element("list-id").value = "5";
  element("request-body").value = "{broken";
  const malicious = '<img src=x onerror="alert(1)">';
  fetchMock.mockResolvedValueOnce(new Response(malicious, { status: 400 }));
  submit("request-form");
  await vi.waitFor(() => expect(element("response-body").textContent).toBe(malicious));
  expect(element("response-body").querySelector("img")).toBeNull();
  expect(fetchMock.mock.calls[0][0]).toBe("http://localhost:8080/api/v1/lists/5/item");
  expect(fetchMock.mock.calls[0][1].body).toBe("{broken");
  expect(element("sent-body").textContent).toBe("{broken");
});

// Generated by Codex and not thoroughly checked for correctness.
test("GitHub return exchanges once, scrubs the callback URL, and displays the saved session", async () => {
  localStorage.setItem(STORAGE_KEY, JSON.stringify({
    origin: "http://localhost:8080", environments: {},
    pendingOAuth: { origin: "http://localhost:8080", started: Date.now() },
  }));
  window.history.replaceState(null, "", "/backend/api-tester.html?code=code-1&state=state-1");
  fetchMock.mockResolvedValueOnce(Response.json({ token: "oauth-session", user: { id: 9, github_username: "signed-in" } }));
  await boot();
  await vi.waitFor(() => expect(element("profile-summary").textContent).toContain("signed-in"));
  expect(fetchMock).toHaveBeenCalledTimes(1);
  expect(new URL(fetchMock.mock.calls[0][0]).searchParams.get("state")).toBe("state-1");
  expect(window.location.search).toBe("");
  expect(element("token").value).toBe("oauth-session");
  expect(element("message").textContent).toContain("Signed in with GitHub");
});

