func TestPracticeRepositoryOwnershipValidationAndQuota(t *testing.T) {
	database := testutil.OpenTestDB(t)
	state := newListItemIntegrationState(t, database)
	original := createIntegrationListItem(t, state.repository, state.ownerID, state.ownerListID, "1900A", 0)
	for _, target := range []struct {
		name      string
		userID    int64
		listID    int64
		problemID string
	}{
		{"foreign list", state.otherUserID, state.ownerListID, original.ProblemId},
		{"missing list", state.ownerID, integrationMissingItemListID, original.ProblemId},
		{"missing item", state.ownerID, state.ownerListID, "absent"},
	} {
		t.Run(target.name, func(t *testing.T) {
			if _, err := state.repository.Update(t.Context(), target.userID, target.listID, target.problemID, practicePatch(t, `{"status":"solved"}`)); !errors.Is(err, listitems.ErrItemNotFound) {
				t.Fatalf("Update(): %v", err)
			}
		})
	}
	for _, body := range []string{`{}`, `{"status":"skipped"}`, `{"help_used":"unknown"}`, `{"solved_on":"2026-02-30"}`, `{"time_spent":-1}`, `{"notes":"` + strings.Repeat("界", 513) + `"}`} {
		patch := practicePatch(t, body)
		if _, err := state.repository.Update(t.Context(), state.ownerID, state.ownerListID, original.ProblemId, patch); !errors.Is(err, listitems.ErrInvalidPractice) {
			t.Fatalf("Update(%s): %v", body, err)
		}
		if !patch.Empty() {
			invalid := original
			invalid.Practice = patch.Values()
			if err := state.repository.Create(t.Context(), state.ownerID, &invalid); !errors.Is(err, listitems.ErrInvalidPractice) {
				t.Fatalf("Create(%s): %v", body, err)
			}
		}
	}
	stored, err := state.repository.GetItems(t.Context(), state.ownerID, state.ownerListID)
	if err != nil {
		t.Fatal(err)
	}
	assertIntegrationListItems(t, stored, []listitems.ListItem{original})
	if _, err := database.ExecContext(t.Context(), `INSERT INTO list_items(list_id, problem_id, position)
		SELECT $1, 'quota-' || n, n FROM generate_series(1, $2::integer) AS n`, state.ownerListID, limits.ItemsPerList-1); err != nil {
		t.Fatal(err)
	}
	duplicate := original
	if err := state.repository.Create(t.Context(), state.ownerID, &duplicate); !errors.Is(err, listitems.ErrItemExists) || !reflect.DeepEqual(duplicate, original) {
		t.Fatalf("duplicate at quota = %+v, error = %v", duplicate, err)
	}
	if err := state.repository.Create(t.Context(), state.ownerID, &listitems.ListItem{ListId: state.ownerListID, ProblemId: "over-quota"}); !errors.Is(err, limits.ErrItemQuota) {
		t.Fatalf("new membership at quota: %v", err)
	}
	if _, err := state.repository.Update(t.Context(), state.ownerID, state.ownerListID, original.ProblemId, practicePatch(t, `{"notes":"Allowed at quota"}`)); err != nil {
		t.Fatal(err)
	}
}

