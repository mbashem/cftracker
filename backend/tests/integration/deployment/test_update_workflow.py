"""Run the actual update coordinator with build and SSH/SCP boundaries replaced."""
from pathlib import Path
import os
import subprocess
import tempfile
import unittest

REPOSITORY_ROOT = Path(__file__).resolve().parents[4]
UPDATE_SCRIPT = REPOSITORY_ROOT / "backend/deploy/vps/update.sh"

class UpdateWorkflowTest(unittest.TestCase):
    # Run the real coordinator with local fixtures replacing build and remote I/O.
    def run_update(self, directory, scenario="success", arguments=None):
        arguments = arguments or ["ubuntu@vps.example.test", "api.example.test", "release-test"]
        script = '''source "$1"
shift
events="$CFTRACKER_BUILD_ROOT/events"
# The real builder is covered separately; create a tiny checksum-valid bundle.
build_bundle() {
  printf 'build\\n' >> "$events"
  [[ $SCENARIO != build-failure ]] || return 71
  mkdir -m 700 "$bundle"
  printf 'test build\\n' > "$bundle/BUILD.txt"
  printf 'image fixture\\n' > "$bundle/images.tar"
  python3 "$root/backend/deploy/vps/bundle_helpers.py" checksums "$bundle"
  if [[ $SCENARIO == checksum-failure ]]; then
    printf 'changed\\n' >> "$bundle/images.tar"
  fi
}
# Never invoke Docker, SSH, or SCP against host services in these tests.
docker() { exit 99; }
scp() {
  printf 'upload\\n' >> "$events"
  [[ $SCENARIO != upload-failure ]]
}
ssh() {
  if [[ ${5:-} == bash ]]; then
    [[ -n ${11:-} ]] || return 99
    stage=${8}
    cat >/dev/null
    printf 'remote:%s\\n' "$stage" >> "$events"
    case "$stage:$SCENARIO" in
      reserve:reserve-failure|install:install-failure) return 76 ;;
    esac
    if [[ $stage == preflight ]]; then
      [[ $SCENARIO != preflight-failure ]] || return 72
      printf '0123456789ab\\n'
    fi
    if [[ $stage == deploy ]]; then
      [[ ${11} == 0123456789ab ]] || return 99
      [[ $SCENARIO != deploy-failure ]] || return 74
    fi
    if [[ $stage == verify && $SCENARIO == verification-failure ]]; then return 75; fi
  elif [[ ${5:-} == *pg_dump* ]]; then
    printf 'export\\n' >> "$events"
    if [[ $SCENARIO == empty-export ]]; then return 0; fi
    printf 'archive fixture'
    [[ $SCENARIO != export-failure ]] || return 72
  elif [[ ${5:-} == *pg_restore* ]]; then
    printf 'inspect\\n' >> "$events"
    [[ $(cat) == 'archive fixture' ]] || return 99
    [[ $SCENARIO != inspection-failure ]] || return 73
  else
    return 99
  fi
}
main "$@"
'''
        environment = dict(os.environ, CFTRACKER_BUILD_ROOT=str(directory / "builds"),
                           CFTRACKER_BACKUP_DIR=str(directory / "backups"), SCENARIO=scenario)
        return subprocess.run(["bash", "-c", script, "update-test", str(UPDATE_SCRIPT), *arguments],
                              env=environment, capture_output=True, text=True)

    # Read ordered stage events emitted by the fixture command boundaries.
    def events(self, directory):
        path = directory / "builds/events"
        return path.read_text().splitlines() if path.exists() else []

    # Verify the real preflight retains argument boundaries after SSH command serialization.
    # Generated by Codex and not thoroughly checked for correctness.
    def test_preflight_arguments_survive_ssh_remote_shell_serialization(self):
        script = '''source "$1"
ssh_target=ubuntu@vps.example.test
hostname=api.example.test
release=release-test
# SSH joins its command arguments into a shell command. Exercise that boundary,
# running the real remote preflight with only administrative dependencies mocked.
ssh() { shift 4; bash -c "$*"; }
sudo() {
  [[ $1 == -n ]] || return 99
  shift
  case "$1" in
    true|test) return 0 ;;
    stat) printf '700\\n' ;;
    docker)
      if [[ $2 == compose ]]; then return 0; fi
      case "${4:-}" in
        '{{.State.Health.Status}}') printf 'healthy\\n' ;;
        '{{.Id}}') printf '0123456789ab\\n' ;;
        *) return 99 ;;
      esac ;;
    *) return 99 ;;
  esac
}
df() { :; }
python3() { :; }
export -f sudo df python3
remote_stage preflight
'''
        with tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as directory:
            result = subprocess.run(["bash", "-c", script, "update-test", str(UPDATE_SCRIPT)],
                                    env=dict(os.environ, HOME=directory), capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stdout, "0123456789ab\n")

    # Verify backup validation precedes deployment and leaves a protected local archive.
    # Generated by Codex and not thoroughly checked for correctness.
    def test_validated_local_archive_precedes_deployment_and_is_protected(self):
        with tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as temporary:
            directory = Path(temporary)
            # The mock's event log is a local test resource, never a remote file.
            (directory / "builds").mkdir()
            result = self.run_update(directory)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(self.events(directory), ["remote:preflight", "build", "remote:reserve",
                                                     "upload", "remote:install", "export", "inspect",
                                                     "remote:deploy", "remote:verify"])
            archive = directory / "backups/release-test.dump"
            self.assertEqual(archive.read_bytes(), b"archive fixture")
            self.assertEqual(archive.stat().st_mode & 0o777, 0o600)
            self.assertEqual(archive.parent.stat().st_mode & 0o777, 0o700)
            self.assertFalse(archive.with_suffix(".dump.partial").exists())
            self.assertIn("Release deployed: release-test", result.stdout)

    # Verify failed export or archive inspection prevents deployment confirmation.
    # Generated by Codex and not thoroughly checked for correctness.
    def test_failed_backup_never_confirms_or_runs_deployment(self):
        for scenario in ("export-failure", "empty-export", "inspection-failure"):
            with self.subTest(scenario=scenario), tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as temporary:
                directory = Path(temporary)
                (directory / "builds").mkdir()
                result = self.run_update(directory, scenario)
                self.assertNotEqual(result.returncode, 0)
                self.assertNotIn("remote:deploy", self.events(directory))
                self.assertNotIn("remote:verify", self.events(directory))
                self.assertFalse((directory / "backups/release-test.dump").exists())
                self.assertTrue((directory / "backups/release-test.dump.partial").exists())

    # Verify existing local outputs are preserved before any remote stage can run.
    # Generated by Codex and not thoroughly checked for correctness.
    def test_existing_local_destinations_are_preserved_before_remote_access(self):
        for destination in ("builds/release-test", "backups/release-test.dump", "backups/release-test.dump.partial"):
            with self.subTest(destination=destination), tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as temporary:
                directory = Path(temporary)
                existing = directory / destination
                existing.parent.mkdir(parents=True)
                existing.write_bytes(b"preserve this")
                result = self.run_update(directory)
                self.assertNotEqual(result.returncode, 0)
                self.assertEqual(existing.read_bytes(), b"preserve this")
                self.assertEqual(self.events(directory), [])

    # Generated by Codex and not thoroughly checked for correctness.
    def test_shared_backup_directory_is_rejected_without_changing_permissions(self):
        for symlink in (False, True):
            with self.subTest(symlink=symlink), tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as temporary:
                directory = Path(temporary)
                (directory / "builds").mkdir()
                shared = directory / ("shared" if symlink else "backups")
                shared.mkdir()
                shared.chmod(0o750)
                if symlink:
                    (directory / "backups").symlink_to(shared, target_is_directory=True)
                old_archive = shared / "previous.dump"
                old_archive.write_bytes(b"preserve this")

                result = self.run_update(directory)

                self.assertNotEqual(result.returncode, 0)
                self.assertIn("Backup directory must be owned by you with mode 700", result.stderr)
                self.assertEqual(shared.stat().st_mode & 0o777, 0o750)
                self.assertEqual(old_archive.read_bytes(), b"preserve this")
                self.assertEqual(list(shared.iterdir()), [old_archive])
                self.assertEqual(self.events(directory), [])

    # Verify each predeployment failure suppresses every dependent stage.
    # Generated by Codex and not thoroughly checked for correctness.
    def test_each_predeployment_failure_stops_all_later_stages(self):
        for scenario, expected_events in (
            ("preflight-failure", ["remote:preflight"]),
            ("build-failure", ["remote:preflight", "build"]),
            ("checksum-failure", ["remote:preflight", "build"]),
            ("reserve-failure", ["remote:preflight", "build", "remote:reserve"]),
            ("upload-failure", ["remote:preflight", "build", "remote:reserve", "upload"]),
            ("install-failure", ["remote:preflight", "build", "remote:reserve", "upload", "remote:install"]),
        ):
            with self.subTest(scenario=scenario), tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as temporary:
                directory = Path(temporary)
                (directory / "builds").mkdir()
                result = self.run_update(directory, scenario)
                self.assertNotEqual(result.returncode, 0)
                self.assertEqual(self.events(directory), expected_events)
                self.assertNotIn("Release deployed:", result.stdout)

    # Verify deployment/verification failures retain the backup and never report success.
    # Generated by Codex and not thoroughly checked for correctness.
    def test_failed_deployment_or_verification_retains_backup_without_reporting_success(self):
        for scenario in ("deploy-failure", "verification-failure"):
            with self.subTest(scenario=scenario), tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as temporary:
                directory = Path(temporary)
                (directory / "builds").mkdir()
                result = self.run_update(directory, scenario)
                self.assertNotEqual(result.returncode, 0)
                self.assertTrue((directory / "backups/release-test.dump").is_file())
                if scenario == "deploy-failure":
                    self.assertNotIn("remote:verify", self.events(directory))
                self.assertNotIn("Release deployed:", result.stdout)

    # Verify remote argument validation rejects shell options and path-shaped input.
    # Generated by Codex and not thoroughly checked for correctness.
    def test_shell_options_and_paths_are_not_accepted_as_remote_arguments(self):
        for arguments in (("-oProxyCommand=bad", "api.example.test", "release-test"),
                          ("ubuntu@vps.example.test", "https://api.example.test", "release-test"),
                          ("ubuntu@vps.example.test", "api.example.test", "../release")):
            with self.subTest(arguments=arguments), tempfile.TemporaryDirectory(prefix="cftracker-update-test-") as temporary:
                directory = Path(temporary)
                result = self.run_update(directory, arguments=list(arguments))
                self.assertNotEqual(result.returncode, 0)
                self.assertEqual(self.events(directory), [])
