"""Check generated configuration through the actual deployment initializer."""
from pathlib import Path
import re
import stat
import subprocess
import sys
import tempfile
import unittest
from urllib.parse import urlsplit

from backend.deploy.vps import server_helpers
from backend.deploy.vps.server_helpers import configuration_contents, validate_origin

class ConfigurationContentsTest(unittest.TestCase):
    def initialize(self, **overrides):
        temporary = tempfile.TemporaryDirectory(prefix="cftracker-config-test-")
        self.addCleanup(temporary.cleanup)
        directory = Path(temporary.name) / "configuration"
        environment = {
            "origins": "https://frontend.example.com,http://localhost:5173",
            "client_id": "test-client-id",
            "client_secret": "test-client-secret",
            "PYTHONDONTWRITEBYTECODE": "1",
        }
        arguments = [sys.executable, str(Path(server_helpers.__file__)),
                     "init", str(directory)]
        result = subprocess.run(arguments, env=environment | overrides,
                                capture_output=True, text=True)
        return directory, arguments, environment | overrides, result

    def environment_values(self, path):
        return dict(line.split("=", 1) for line in path.read_text().splitlines())

    def contents(self, **overrides):
        values = {
            "origins": "https://frontend.example.com,http://localhost:5173",
            "client_id": "test-client-id",
            "client_secret": "test-client-secret",
            "admin": "admin-fixture",
            "app": "app-fixture",
            "jwt": "jwt-fixture",
        }
        return configuration_contents(**(values | overrides))

    # Generated by Codex and not thoroughly checked for correctness.
    def test_admin_credentials_are_separate_from_application_configuration(self):
        directory, _, _, result = self.initialize()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual({path.name for path in directory.iterdir()},
                         {"postgres-password", "app-password", "backend.env", "migration.env"})
        admin = (directory / "postgres-password").read_text().strip()
        app = (directory / "app-password").read_text().strip()
        self.assertRegex(admin, r"^[0-9a-f]{64}$")
        self.assertRegex(app, r"^[0-9a-f]{64}$")
        self.assertNotEqual(admin, app)
        backend = self.environment_values(directory / "backend.env")
        migration = self.environment_values(directory / "migration.env")
        app_url = urlsplit(backend["DATABASE_URL"])
        admin_url = urlsplit(migration["MIGRATION_DATABASE_URL"])
        self.assertEqual((app_url.username, app_url.password), ("cftracker_app", app))
        self.assertEqual((admin_url.username, admin_url.password), ("postgres", admin))
        for url in (app_url, admin_url):
            self.assertEqual((url.hostname, url.port, url.path, url.query),
                             ("postgres", 5432, "/cftracker", "sslmode=disable"))
        self.assertNotIn(admin, (directory / "backend.env").read_text())
        self.assertNotIn(app, (directory / "migration.env").read_text())
        for secret in (admin, app, backend["JWT_SECRET"], "test-client-secret"):
            self.assertNotIn(secret, result.stdout + result.stderr)

    # Generated by Codex and not thoroughly checked for correctness.
    def test_written_backend_environment_contains_oauth_settings_without_fixed_redirect(self):
        directory, _, _, result = self.initialize()
        self.assertEqual(result.returncode, 0, result.stderr)
        backend = (directory / "backend.env").read_text()
        self.assertNotIn("GITHUB_REDIRECT_URL", backend)
