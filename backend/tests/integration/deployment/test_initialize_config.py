"""Exercise initializer failures using the real CLI and temporary files."""
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from backend.deploy.vps import server_helpers

class InitializeConfigTest(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="cftracker-init-test-")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.directory = self.root / "configuration"
        self.environment = {
            "origins": "https://frontend.example.com,http://localhost:5173",
            "client_id": "test-client-id",
            "client_secret": "test-client-secret",
            "PYTHONDONTWRITEBYTECODE": "1",
        }

    def initialize(self, **overrides):
        return subprocess.run([
            sys.executable, str(Path(server_helpers.__file__)),
            "init", str(self.directory),
        ], env=self.environment | overrides, capture_output=True, text=True)

    # Generated by Codex and not thoroughly checked for correctness.
    def test_any_existing_credential_prevents_all_file_writes(self):
        names = ("postgres-password", "app-password", "backend.env", "migration.env")
        self.directory.mkdir()
        for name in names:
            with self.subTest(existing=name):
                existing = self.directory / name
                existing.write_bytes(b"existing credential\n")
                result = self.initialize()
                self.assertNotEqual(result.returncode, 0)
                self.assertIn("Configuration already exists", result.stderr)
                self.assertEqual(list(self.directory.iterdir()), [existing])
                self.assertEqual(existing.read_bytes(), b"existing credential\n")
                existing.unlink()

    # Generated by Codex and not thoroughly checked for correctness.
    def test_invalid_settings_fail_before_directory_or_file_changes(self):
        result = self.initialize(origins="https://frontend.example.com/path")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Origins must", result.stderr)
        self.assertFalse(self.directory.exists())

    # Generated by Codex and not thoroughly checked for correctness.
    def test_non_directory_destination_preserves_existing_file(self):
        self.directory.write_bytes(b"do not replace")
        result = self.initialize()
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(self.directory.read_bytes(), b"do not replace")
        self.assertEqual(list(self.root.iterdir()), [self.directory])

    # Generated by Codex and not thoroughly checked for correctness.
    def test_exclusive_create_failure_stops_remaining_writes(self):
        self.directory.mkdir()
        migration = self.directory / "migration.env"
        missing_target = self.root / "missing-secret"
        migration.symlink_to(missing_target)
        result = self.initialize()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("FileExistsError", result.stderr)
        self.assertTrue(migration.is_symlink())
        self.assertFalse(missing_target.exists())
        self.assertFalse((self.directory / "backend.env").exists())
        self.assertEqual(len((self.directory / "postgres-password").read_text().strip()), 64)
        self.assertNotIn("Configuration created", result.stdout)
