"""Exercise the server's redirect validation with curl replaced at the boundary."""
from pathlib import Path
import subprocess
import unittest

SERVER_SCRIPT = Path(__file__).resolve().parents[4] / "backend/deploy/vps/server.sh"

class HttpRedirectTest(unittest.TestCase):
    def run_http_redirect_check(self, response, curl_status=0):
        redirect_check_script = '''source "$1"
# Capture fixture values before curl receives its own positional arguments.
fixture_response=$2
fixture_status=$3
unexpected_curl_arguments() {
  printf 'Unexpected curl arguments: %s\n' "$*" >&2
  exit 99
}
curl() {
  local host='' output='' format='' url=''
  # Inspect argument boundaries while allowing harmless option reordering.
  # Unknown options include redirect-following flags, which would hide failures.
  while (( $# )); do
    case "$1" in
      --fail|--silent|--show-error) shift ;;
      -H|--header)
        [[ ${2:-} == 'Host: api.example.com' ]] || unexpected_curl_arguments "$@"
        host=$2; shift 2 ;;
      --output)
        [[ ${2:-} == /dev/null ]] || unexpected_curl_arguments "$@"
        output=$2; shift 2 ;;
      --write-out)
        [[ ${2:-} == '%{http_code} %{redirect_url}' ]] || unexpected_curl_arguments "$@"
        format=$2; shift 2 ;;
      http://127.0.0.1/health/ready)
        [[ -z $url ]] || unexpected_curl_arguments "$@"
        url=$1; shift ;;
      *) unexpected_curl_arguments "$@" ;;
    esac
  done
  [[ -n $host && -n $output && -n $format && -n $url ]] || \
    unexpected_curl_arguments 'Missing Host header, output destination, write-out format, or request URL.'
  printf '%s' "$fixture_response"
  return "$fixture_status"
}
check_http_redirect api.example.com
'''
        return subprocess.run(
            ["bash", "-c", redirect_check_script, "redirect-test",
             str(SERVER_SCRIPT), response, str(curl_status)],
            capture_output=True, text=True,
        )

    # Generated by Codex and not thoroughly checked for correctness.
    def test_accepts_permanent_redirect_to_expected_https_url(self):
        for status in (301, 308):
            with self.subTest(status=status):
                result = self.run_http_redirect_check(f"{status} https://api.example.com/health/ready")
                self.assertEqual(result.returncode, 0, result.stderr)

    # Generated by Codex and not thoroughly checked for correctness.
    def test_rejects_missing_temporary_or_misdirected_redirect(self):
        for response in (
            "200 ", "301 ", "302 https://api.example.com/health/ready",
            "301 https://other.example.com/health/ready",
            "301 http://api.example.com/health/ready",
            "301 https://api.example.com/other",
        ):
            with self.subTest(response=response):
                result = self.run_http_redirect_check(response)
                self.assertEqual(result.returncode, 1)
                self.assertIn("HTTP must permanently redirect", result.stderr)

    # Generated by Codex and not thoroughly checked for correctness.
    def test_propagates_curl_failure_even_with_expected_response(self):
        result = self.run_http_redirect_check("301 https://api.example.com/health/ready", curl_status=7)
        self.assertEqual(result.returncode, 7)
