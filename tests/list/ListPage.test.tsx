import { setupFrontendTests } from "../support/frontendTestSetup";
import { frontend } from "../support/frontendMocks";
import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { expect, test } from "vitest";
import ListPage from "../../src/components/list/ListPage";
import { createRouterWrapper, LocationProbe } from "../support/router";
import { createList } from "../support/listFixtures";

setupFrontendTests(() => {
  frontend.lists = [createList()];
  frontend.individualList = frontend.lists[0];
});
function page(entry = "/lists?listId=5&keep=yes") {
  return render(<><ListPage /><LocationProbe /></>, { wrapper: createRouterWrapper(entry) });
}
function openCreate() { fireEvent.click(screen.getByRole("button", { name: "Create new list" })); }
function openRename() { fireEvent.click(screen.getByRole("button", { name: "Edit list" })); }
function openDelete() { openRename(); fireEvent.click(screen.getByRole("button", { name: "Delete list" })); }

const nameDialogs = [
  { action: "create", open: openCreate, label: "List Name", submit: "Create List", value: "練習 list", error: "Duplicate name", mutation: frontend.createList, args: ["練習 list"] },
  { action: "rename", open: openRename, label: "Enter New Name", submit: "Update List", value: "Renamed", error: "Rename denied", mutation: frontend.updateListName, args: [5, "Renamed"] },
];

// Generated by Codex and not thoroughly checked for correctness.
test("empty collections render without selected-list actions", () => {
  frontend.lists = [];
  page("/lists");
  expect(screen.queryByRole("button", { name: "Add Problem" })).toBeNull();
  expect(screen.queryByRole("table")).toBeNull();
  expect(screen.getByRole("button", { name: "Create new list" })).toBeDefined();
});

// Generated by Codex and not thoroughly checked for correctness.
test("collection loading and failures are visible", () => {
  frontend.listsLoading = true;
  const view = page();
  expect(screen.getByLabelText("three-dots-loading")).toBeDefined();
  frontend.listsLoading = false;
  frontend.listsError = { status: 401 };
  frontend.lists = [];
  view.rerender(<><ListPage /><LocationProbe /></>);
  expect(screen.getByRole("alert").textContent).toBe("Failed to load lists.");
  expect(screen.queryByLabelText("three-dots-loading")).toBeNull();
});

// Generated by Codex and not thoroughly checked for correctness.
test.each(nameDialogs)("$action submits its name and closes on success", async ({ open, label, submit, value, mutation, args }) => {
  page(); open();
  if (label === "Enter New Name") expect((screen.getByLabelText(label) as HTMLInputElement).value).toBe("Practice");
  fireEvent.change(screen.getByLabelText(label), { target: { value } });
  fireEvent.click(screen.getByRole("button", { name: submit }));
  await waitFor(() => expect(screen.queryByLabelText(label)).toBeNull());
  expect(mutation).toHaveBeenCalledExactlyOnceWith(...args);
});

// Generated by Codex and not thoroughly checked for correctness.
test.each(nameDialogs)("$action failure preserves edited text and allows retry", async ({ open, label, submit, value, error, mutation, args }) => {
  mutation.mockRejectedValueOnce(new Error(error));
  page(); open();
  fireEvent.change(screen.getByLabelText(label), { target: { value } });
  fireEvent.click(screen.getByRole("button", { name: submit }));
  await waitFor(() => expect(frontend.showErrorToast).toHaveBeenCalledWith(error));
  expect((screen.getByLabelText(label) as HTMLInputElement).value).toBe(value);
  fireEvent.click(screen.getByRole("button", { name: submit }));
  await waitFor(() => expect(screen.queryByLabelText(label)).toBeNull());
  expect(mutation).toHaveBeenCalledTimes(2);
  expect(mutation).toHaveBeenLastCalledWith(...args);
});

// Generated by Codex and not thoroughly checked for correctness.
test("canceling deletion preserves the selected list without sending a mutation", async () => {
  page(); openDelete();
  fireEvent.click(screen.getByRole("button", { name: "No" }));
  await waitFor(() => expect(screen.queryByRole("button", { name: "Yes" })).toBeNull());
  expect(frontend.deleteList).not.toHaveBeenCalled();
  expect(screen.getByTestId("location").textContent).toBe("/lists?listId=5&keep=yes");
  expect(screen.getByLabelText("Enter New Name")).toBeDefined();
});

// Generated by Codex and not thoroughly checked for correctness.
test("confirmed deletion clears the selected content and preserves unrelated URL parameters", async () => {
  page(); openDelete();
  fireEvent.click(screen.getByRole("button", { name: "Yes" }));
  await waitFor(() => expect(screen.queryByRole("button", { name: "Add Problem" })).toBeNull());
  expect(frontend.deleteList).toHaveBeenCalledExactlyOnceWith(5);
  expect(screen.getByTestId("location").textContent).toBe("/lists?keep=yes");
  expect(screen.queryByRole("table")).toBeNull();
});

// Generated by Codex and not thoroughly checked for correctness.
test("failed deletion keeps its confirmation open and selection intact for retry", async () => {
  frontend.deleteList.mockRejectedValueOnce(new Error("Delete denied"));
  page(); openDelete();
  fireEvent.click(screen.getByRole("button", { name: "Yes" }));
  await waitFor(() => expect(frontend.showErrorToast).toHaveBeenCalledWith("Delete denied"));
  expect(screen.getByRole("button", { name: "Yes" })).toBeDefined();
  expect(screen.getByTestId("location").textContent).toContain("listId=5");
  fireEvent.click(screen.getByRole("button", { name: "Yes" }));
  await waitFor(() => expect(screen.getByTestId("location").textContent).toBe("/lists?keep=yes"));
});
