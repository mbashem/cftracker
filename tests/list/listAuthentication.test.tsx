import { authenticatedUser, backendList, listApi, setupBackendMock } from "../support/backendMocks";
import { act, cleanup, renderHook, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import useListApi from "../../src/data/hooks/useListApi";
import { removeUser } from "../../src/data/reducers/userSlice";
import { StorageService } from "../../src/util/StorageService";

let backend: ReturnType<typeof setupBackendMock>;
beforeEach(() => {
  localStorage.clear();
  backend = setupBackendMock();
  vi.spyOn(console, "log").mockImplementation(() => {});
});
afterEach(() => { cleanup(); backend.dispose(); localStorage.clear(); vi.restoreAllMocks(); });

// Generated by Codex and not thoroughly checked for correctness.
test("mounted list queries follow authentication state and never fetch while signed out", async () => {
  backend.fetchMock.mockImplementation(async input => {
    const request = new Request(input);
    backend.requests.push(request);
    return Response.json(new URL(request.url).pathname.endsWith("/5")
      ? { list: backendList, items: [] } : { lists: [backendList] });
  });
  const hook = renderHook(() => {
    const api = useListApi();
    return { collection: api.useGetAllListsQuery(), list: api.useGetListQuery(5) };
  }, { wrapper: backend.wrapper });
  expect(backend.requests).toHaveLength(0);
  act(() => { backend.authenticate(); });
  await waitFor(() => expect(hook.result.current.list.data?.id).toBe(5));
  await waitFor(() => expect(hook.result.current.collection.data).toHaveLength(1));
  const count = backend.requests.length;
  act(() => { backend.store.dispatch(removeUser()); });
  expect(hook.result.current.list.data).toBeUndefined();
  expect(hook.result.current.collection.data).toBeUndefined();
  expect(StorageService.getJWTToken()).toBeNull();
  await act(async () => {});
  expect(backend.requests).toHaveLength(count);
});

// Generated by Codex and not thoroughly checked for correctness.
test("direct queries and mutations are blocked without authentication", async () => {
  await expect(backend.store.dispatch(listApi.endpoints.getList.initiate(5)).unwrap()).rejects.toMatchObject({ status: 401 });
  await expect(backend.store.dispatch(listApi.endpoints.createList.initiate({ name: "Private" })).unwrap()).rejects.toMatchObject({ status: 401 });
  expect(backend.fetchMock).not.toHaveBeenCalled();
});

// Generated by Codex and not thoroughly checked for correctness.
test("account changes clear cached lists and fetch with the new session token", async () => {
  backend.authenticate();
  backend.respond({ lists: [backendList] });
  const subscription = backend.store.dispatch(listApi.endpoints.getAllLists.initiate());
  await subscription.unwrap();
  subscription.unsubscribe();
  backend.authenticate({ ...authenticatedUser, id: 8, jwtToken: "second-session" });
  expect(backend.store.getState().listApi.queries).toEqual({});
  backend.respond({ lists: [] });
  const lists = await backend.store.dispatch(listApi.endpoints.getAllLists.initiate()).unwrap();
  expect(lists).toEqual([]);
  expect(backend.requests[backend.requests.length - 1]?.headers.get("Authorization")).toBe("Bearer second-session");
});

// Generated by Codex and not thoroughly checked for correctness.
test("a response completing after logout cannot repopulate the private cache", async () => {
  backend.authenticate();
  let resolve!: (value: Response) => void;
  backend.fetchMock.mockImplementationOnce(() => new Promise(done => { resolve = done; }));
  const pending = backend.store.dispatch(listApi.endpoints.getAllLists.initiate());
  await vi.waitFor(() => expect(backend.fetchMock).toHaveBeenCalledTimes(1));
  backend.store.dispatch(removeUser());
  resolve(Response.json({ lists: [backendList] }));
  await pending;
  expect(backend.store.getState().listApi.queries).toEqual({});
});
