import { backendList, listApi, setupBackendMock } from "../support/backendMocks";
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, test } from "vitest";
import { MemoryRouter } from "react-router";
import ProblemListPicker from "../../src/components/problem/ProblemListPicker";
import { LocationProbe } from "../support/router";
import { removeUser } from "../../src/data/reducers/userSlice";

let backend: ReturnType<typeof setupBackendMock>;
beforeEach(() => { localStorage.clear(); backend = setupBackendMock(); });
afterEach(() => { cleanup(); backend.dispose(); localStorage.clear(); });
function page() {
  render(<MemoryRouter initialEntries={["/problems?q=dp"]}><ProblemListPicker /><LocationProbe /></MemoryRouter>, { wrapper: backend.wrapper });
}

// Generated by Codex and not thoroughly checked for correctness.
test("the picker fetches only after first click, selects a list, and preserves problem filters", async () => {
  backend.authenticate(); backend.respond({ lists: [backendList] }); page();
  expect(backend.fetchMock).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button", { name: "Add problems to a list" }));
  fireEvent.click(await screen.findByRole("button", { name: "Practice" }));
  expect(backend.requests).toHaveLength(1);
  expect(screen.getByTestId("location").textContent).toBe("/problems?q=dp&listId=5");
  fireEvent.click(screen.getByRole("button", { name: "Change list" }));
  await screen.findByRole("button", { name: "Practice" });
  expect(backend.requests).toHaveLength(1);
  fireEvent.click(screen.getByRole("button", { name: "Stop adding to list" }));
  expect(screen.getByTestId("location").textContent).toBe("/problems?q=dp");
});

// Generated by Codex and not thoroughly checked for correctness.
test("opening the picker reuses lists already cached by the Lists page", async () => {
  backend.authenticate(); backend.respond({ lists: [backendList] });
  const request = backend.store.dispatch(listApi.endpoints.getAllLists.initiate());
  await request.unwrap(); request.unsubscribe();
  backend.fetchMock.mockClear(); page();
  fireEvent.click(screen.getByRole("button", { name: "Add problems to a list" }));
  await screen.findByRole("button", { name: "Practice" });
  expect(backend.fetchMock).not.toHaveBeenCalled();
});

// Generated by Codex and not thoroughly checked for correctness.
test("anonymous users do not see a picker and make no list requests", () => {
  page(); expect(screen.queryByRole("button")).toBeNull();
  expect(backend.fetchMock).not.toHaveBeenCalled();
});

// Generated by Codex and not thoroughly checked for correctness.
test("empty and failed list responses offer creation or retry", async () => {
  backend.authenticate(); backend.respond({ error: "Unavailable" }, 500); page();
  fireEvent.click(screen.getByRole("button", { name: "Add problems to a list" }));
  await screen.findByRole("alert");
  backend.respond({ lists: [] });
  fireEvent.click(screen.getByRole("button", { name: "Retry" }));
  expect((await screen.findByRole("link", { name: "Create a list" })).getAttribute("href")).toBe("/lists");
});

// Generated by Codex and not thoroughly checked for correctness.
test("logging out closes the picker and a delayed list response cannot show private names", async () => {
  backend.authenticate();
  let resolve!: (value: Response) => void;
  backend.fetchMock.mockImplementationOnce(() => new Promise(done => { resolve = done; }));
  page(); fireEvent.click(screen.getByRole("button", { name: "Add problems to a list" }));
  await waitFor(() => expect(backend.fetchMock).toHaveBeenCalledTimes(1));
  act(() => { backend.store.dispatch(removeUser()); });
  await act(async () => { resolve(Response.json({ lists: [backendList] })); });
  expect(screen.queryByRole("button")).toBeNull();
  expect(screen.queryByText("Practice")).toBeNull();
});
