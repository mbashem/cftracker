test("failed item mutations preserve membership and remain retryable", async () => {
  const hook = setup();
  await waitFor(() => expect(hook.result.current.page.list?.id).toBe(5));
  frontend.addProblemToList.mockRejectedValueOnce(new Error("Add denied"));
  frontend.deleteProblemFromList.mockRejectedValueOnce(new Error("Remove denied"));
  await act(async () => {
    await expect(hook.result.current.page.addProblemToList("100B")).rejects.toThrow("Add denied");
    await expect(hook.result.current.page.deleteProblemFromList("100A")).rejects.toThrow("Remove denied");
  });
  expect([...hook.result.current.page.problemsAddedToList]).toEqual(["100A"]);
  await act(async () => { await hook.result.current.page.addProblemToList("100B"); });
  expect(hook.result.current.page.problemsAddedToList.has("100B")).toBe(true);
});

// Generated by Codex and not thoroughly checked for correctness.
test("superseded list responses cannot overwrite the new list and leaving list mode clears membership", async () => {
  let resolveOld!: (value: ListWithItem) => void;
  frontend.getListWithItems.mockImplementationOnce(() => new Promise(resolve => { resolveOld = resolve; }));
  frontend.getListWithItems.mockResolvedValueOnce({ ...list, id: 6, name: "Second", items: [] });
  const hook = setup();
  act(() => { void hook.result.current.navigate("/problems?listId=6&useFilterStorage=false"); });
  await waitFor(() => expect(hook.result.current.page.list?.id).toBe(6));
  await act(async () => { resolveOld(list); });
  expect(hook.result.current.page.list?.id).toBe(6);
  expect([...hook.result.current.page.problemsAddedToList]).toEqual([]);
  act(() => { void hook.result.current.navigate("/problems?useFilterStorage=false"); });
  expect(hook.result.current.page.showAddToList).toBe(false);
  expect(hook.result.current.page.list).toBeUndefined();
});

