test.each(["resolve", "reject"])("a mutation that completes with %s after logout cannot restore membership or report a stale error", async outcome => {
  const hook = setup();
  await waitFor(() => expect(hook.result.current.page.list?.id).toBe(5));
  let finish!: (value: typeof list.items[number]) => void;
  let fail!: (error: Error) => void;
  frontend.addProblemToList.mockImplementationOnce(() => new Promise((done, reject) => { finish = done; fail = reject; }));
  let pending!: Promise<void>;
  act(() => { pending = hook.result.current.page.addProblemToList("100B"); });
  frontend.authenticated = false;
  hook.rerender();
  await act(async () => {
    if (outcome === "resolve") finish({ listId: 5, problemId: "100B", position: 5, createdAt: "2026-01-01" });
    else fail(new Error("Old session rejected"));
    await pending;
  });
  expect(hook.result.current.page.list).toBeUndefined();
  expect([...hook.result.current.page.problemsAddedToList]).toEqual([]);
  expect(hook.result.current.page.showAddToList).toBe(false);
});
