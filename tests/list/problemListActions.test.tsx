test("authentication changes clear private state and sign-in reloads the same list without changing filters", async () => {
  const hook = setup("/problems?listId=5&useFilterStorage=false&q=Alpha");
  await waitFor(() => expect(hook.result.current.page.list?.name).toBe("Practice"));
  frontend.authenticated = false;
  hook.rerender();
  expect(hook.result.current.page.list).toBeUndefined();
  expect(hook.result.current.page.showAddToList).toBe(false);
  expect([...hook.result.current.page.problemsAddedToList]).toEqual([]);
  await act(async () => {
    await hook.result.current.page.addProblemToList("100B");
    await hook.result.current.page.deleteProblemFromList("100A");
  });
  expect(frontend.addProblemToList).not.toHaveBeenCalled();
  expect(frontend.deleteProblemFromList).not.toHaveBeenCalled();
  expect(frontend.getListWithItems).toHaveBeenCalledTimes(1);
  const filter = hook.result.current.page.filter;
  expect(filter.search).toBe("Alpha");
  frontend.authenticated = true;
  frontend.userId = 2;
  frontend.getListWithItems.mockResolvedValue({ ...list, userId: 2, name: "Second account", items: [] });
  hook.rerender();
  await waitFor(() => expect(hook.result.current.page.list?.name).toBe("Second account"));
  expect(frontend.getListWithItems).toHaveBeenCalledTimes(2);
  expect(hook.result.current.page.filter).toEqual(filter);
  expect([...hook.result.current.page.problemsAddedToList]).toEqual([]);
});

