import { frontend, resetFrontendMocks } from "../support/frontendMocks";
import { act, cleanup, renderHook, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, test } from "vitest";
import { useNavigate } from "react-router";
import useProblemPage from "../../src/components/problem/useProblemPage";
import { seedProblemFixtures } from "../support/problemFixtures";
import { createRouterWrapper } from "../support/router";
import type { ListWithItem } from "../../src/types/list";

const list: ListWithItem = { id: 5, userId: 1, name: "Practice", createdAt: "2026-01-01", items: [
  { listId: 5, problemId: "100A", position: 4, createdAt: "2026-01-01" },
] };
beforeEach(() => {
  resetFrontendMocks(); localStorage.clear(); seedProblemFixtures();
  frontend.getListWithItems.mockResolvedValue(list);
});
afterEach(() => { cleanup(); localStorage.clear(); });
function setup(entry = "/problems?listId=5&useFilterStorage=false") {
  return renderHook(() => ({ page: useProblemPage(), navigate: useNavigate() }), { wrapper: createRouterWrapper(entry) });
}

// Generated by Codex and not thoroughly checked for correctness.
test("list item controls initialize from membership and append after the highest existing position", async () => {
  const hook = setup();
  await waitFor(() => expect(hook.result.current.page.problemsAddedToList.has("100A")).toBe(true));
  await act(async () => { await hook.result.current.page.addProblemToList("100B"); });
  expect(frontend.addProblemToList).toHaveBeenCalledExactlyOnceWith(5, "100B", 5);
  expect([...hook.result.current.page.problemsAddedToList]).toEqual(["100A", "100B"]);
  await act(async () => { await hook.result.current.page.deleteProblemFromList("100A"); });
  expect(frontend.deleteProblemFromList).toHaveBeenCalledExactlyOnceWith(5, "100A");
  expect([...hook.result.current.page.problemsAddedToList]).toEqual(["100B"]);
  expect(hook.result.current.page.list?.items.map(item => item.problemId)).toEqual(["100B"]);
});

