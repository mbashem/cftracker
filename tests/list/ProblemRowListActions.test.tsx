test("an add failure is visible and retry adds the problem once", async () => {
  rejectAddition = true; page();
  fireEvent.click(screen.getByRole("button", { name: "Add 100A to a list" }));
  fireEvent.click(await screen.findByRole("button", { name: "Add 100A to Practice" }));
  expect((await screen.findByRole("alert")).textContent).toBe("Permission denied");
  rejectAddition = false;
  fireEvent.click(screen.getByRole("button", { name: "Add 100A to Practice" }));
  await screen.findByText("Added 100A to Practice.");
  expect(items.filter(item => item.problem_id === "100A")).toHaveLength(1);
});

