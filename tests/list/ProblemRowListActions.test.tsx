import { backendList, setupBackendMock } from "../support/backendMocks";
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import { MemoryRouter } from "react-router";
import ProblemTable from "../../src/components/problem/problem-list/ProblemTable";
import Problem from "../../src/types/CF/Problem";
import Theme, { ThemesType } from "../../src/util/Theme";
import { SortOrder, SortProblemBy } from "../../src/util/sortMethods";
import { removeUser } from "../../src/data/reducers/userSlice";

let backend: ReturnType<typeof setupBackendMock>;
let items: { list_id: number; problem_id: string; position: number; created_at: string }[];
let rejectAddition: boolean;

beforeEach(() => {
  localStorage.clear(); backend = setupBackendMock(); backend.authenticate(); rejectAddition = false;
  items = [{ list_id: 5, problem_id: "100B", position: 4, created_at: "2026-01-01" }];
  vi.spyOn(console, "log").mockImplementation(() => {});
  backend.fetchMock.mockImplementation(async input => {
    const request = new Request(input); backend.requests.push(request);
    const path = new URL(request.url).pathname;
    if (path === "/api/v1/lists") return Response.json({ lists: [backendList] });
    if (request.method === "PUT") {
      if (rejectAddition) return Response.json({ error: "Permission denied" }, { status: 403 });
      const body = await request.clone().json();
      const item = { list_id: 5, ...body, created_at: "2026-01-02" };
      items = [...items, item];
      return Response.json({ item }, { status: 201 });
    }
    return Response.json({ list: backendList, items });
  });
});
afterEach(() => { cleanup(); backend.dispose(); localStorage.clear(); vi.restoreAllMocks(); });

function page() {
  render(<MemoryRouter><ProblemTable
    problems={[new Problem(100, "A", "Alpha", "PROGRAMMING", 800, []), new Problem(100, "B", "Beta", "PROGRAMMING", 900, [])]}
    perPage={25} pageSelected={0} theme={new Theme(ThemesType.LIGHT)}
    filterState={{ sortBy: SortProblemBy.Id, order: SortOrder.Ascending, tags: new Set() }}
    solved={new Set()} attempted={new Set()} showAddToList={false} showListPicker
    problemsAddedToList={new Set()} sortList={() => {}} addToList={() => {}} deleteFromList={() => {}}
  /></MemoryRouter>, { wrapper: backend.wrapper });
}

// Generated by Codex and not thoroughly checked for correctness.
test("each row opens its own chooser lazily and adds that problem after the highest list position", async () => {
  page();
  expect(backend.requests).toHaveLength(0);
  fireEvent.click(screen.getByRole("button", { name: "Add 100A to a list" }));
  fireEvent.click(await screen.findByRole("button", { name: "Add 100A to Practice" }));
  await screen.findByText("Added 100A to Practice.");
  const additions = backend.requests.filter(request => request.method === "PUT");
  expect(additions).toHaveLength(1);
  expect(new URL(additions[0].url).pathname).toBe("/api/v1/lists/5/item");
  expect(await additions[0].json()).toEqual({ problem_id: "100A", position: 5 });
  expect(additions[0].headers.get("Authorization")).toBe("Bearer test-session");
  expect((screen.getByRole("button", { name: "Added 100A to Practice" }) as HTMLButtonElement).disabled).toBe(true);
  fireEvent.click(screen.getByRole("button", { name: "Close" }));
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
  fireEvent.click(screen.getByRole("button", { name: "Add 100B to a list" }));
  fireEvent.click(await screen.findByRole("button", { name: "Add 100B to Practice" }));
  await screen.findByText("100B is already in Practice.");
  expect(backend.requests.filter(request => request.method === "PUT")).toHaveLength(1);
  expect(backend.requests.filter(request => new URL(request.url).pathname === "/api/v1/lists")).toHaveLength(1);
});

