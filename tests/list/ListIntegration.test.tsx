function handleListRequests(handler: (request: Request) => Response | Promise<Response>) {
  backend.handleRequests(request => {
    const path = requestPath(request);
    if (path.endsWith("/problemset.problems")) return Response.json({ status: "OK", result: { problems: [], problemStatistics: [] } });
    if (path.endsWith("/related.json")) return Response.json({ status: "OK", result: [] });
    return handler(request);
  });
}

