// Generated by Codex and not thoroughly checked for correctness.
test.each([ThemesType.LIGHT, ThemesType.DARK])("theme %s offers the opposite theme without changing the route", (theme) => {
  frontend.theme = new Theme(theme);
  setup();
  fireEvent.click(screen.getByTitle("Change Theme"));
  expect(frontend.changeThemeMod).toHaveBeenCalledWith(theme === ThemesType.LIGHT ? ThemesType.DARK : ThemesType.LIGHT);
  expect(screen.getByTestId("location").textContent).toBe("/problems");
});

// Generated by Codex and not thoroughly checked for correctness.
test("information popover identifies the creator and source repository", async () => {
  setup();
  fireEvent.click(screen.getByTitle("Created by Bashem"));
  const creator = await screen.findByRole("link", { name: "bashem" });
  expect(creator.getAttribute("href")).toBe("https://codeforces.com/profile/bashem");
  const popover = creator.closest<HTMLElement>('[role="tooltip"]')!;
  const source = within(popover).getAllByRole("link").find((link) => link.getAttribute("href")?.includes("github.com"));
  expect(source?.getAttribute("href")).toBe("https://github.com/mbashem/cftracker");
  expect(screen.getByTestId("location").textContent).toBe("/problems");
});

