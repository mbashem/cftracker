import { frontend, resetFrontendMocks } from "../support/frontendMocks";
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { afterEach, beforeEach, expect, test } from "vitest";
import Menu from "../../src/components/Menu";
import Theme, { ThemesType } from "../../src/util/Theme";
import { createRouterWrapper, LocationProbe } from "../support/router";

beforeEach(() => { resetFrontendMocks(); localStorage.clear(); });
afterEach(cleanup);

function setup() {
  return render(<><Menu /><LocationProbe /></>, { wrapper: createRouterWrapper("/problems") });
}

