test("FE-004 contest search edits replace history and preserve unrelated parameters", async () => {
  setup("/problems?useFilterStorage=false&q=Alpha");
  await act(async () => navigation.navigate("/contests?extra=keep"));
  const input = screen.getByPlaceholderText("Search by Contest Name or Id");
  for (const search of ["Round", "101", ""]) {
    fireEvent.change(input, { target: { value: search } });
    const params = new URLSearchParams(navigation.search);
    expect(params.get("extra")).toBe("keep");
    expect(params.get("q")).toBe(search || null);
  }
  await act(async () => navigation.navigate(-1));
  expect(navigation.pathname).toBe("/problems");
  expect(screen.getByRole("link", { name: "Alpha Dynamic" })).toBeDefined();
  await act(async () => navigation.navigate(1));
  expect(navigation.pathname).toBe("/contests");
  expect(new URLSearchParams(navigation.search).get("extra")).toBe("keep");
});

