async function checkProblemHistory(destination: "Stats" | "Contests", path: string) {
  setup("/problems?useFilterStorage=false&q=Alpha&extra=keep");
  expect(await screen.findByRole("link", { name: "Alpha Dynamic" })).toBeDefined();
  fireEvent.change(screen.getByPlaceholderText("Problem Name or Id"), { target: { value: "Beta" } });
  expect(screen.getByRole("link", { name: "Beta Graph" })).toBeDefined();
  expect(new URLSearchParams(navigation.search).get("extra")).toBe("keep");
  fireEvent.click(screen.getByRole("link", { name: destination }));
  await assertRoute(path);
  await act(async () => navigation.navigate(-1));
  expect(navigation.pathname).toBe("/problems");
  expect(screen.getByRole("link", { name: "Beta Graph" })).toBeDefined();
  expect((screen.getByPlaceholderText("Problem Name or Id") as HTMLInputElement).value).toBe("Beta");
  expect(new URLSearchParams(navigation.search).get("extra")).toBe("keep");
  await act(async () => navigation.navigate(1));
  await assertRoute(path);
}

