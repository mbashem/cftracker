let navigation: NavigationState;
beforeEach(() => {
  resetFrontendMocks();
  localStorage.clear();
  seedProblemFixtures();
  lazyPage.pending = undefined;
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); });

function setup(entry: string) {
  return render(<MemoryRouter initialEntries={[entry]}>
    <NavigationProbe onChange={(state) => { navigation = state; }} />
    <App />
  </MemoryRouter>);
}

async function assertRoute(path: string) {
  if (path === "/problems" || path === "/problems/random") {
    expect(await screen.findByPlaceholderText("Problem Name or Id")).toBeDefined();
  } else if (path === "/contests") {
    expect(await screen.findByPlaceholderText("Search by Contest Name or Id")).toBeDefined();
  } else {
    const heading = ({ "/": "Home page", "/stats": "Stats page", "/comments": "Comments page", "/lists": "Lists page" })[path];
    expect(await screen.findByRole("heading", { name: heading })).toBeDefined();
  }
}

