test("picker buttons focus inputs when native showPicker is unavailable", () => {
  setup();
  const input = screen.getByLabelText("min date");
  Object.defineProperty(input, "showPicker", { configurable: true, value: undefined });
  fireEvent.click(screen.getByRole("button", { name: "Open min date picker" }));
  expect(document.activeElement).toBe(input);
});

