beforeEach(() => { resetFrontendMocks(); localStorage.clear(); seedProblemFixtures(); });
afterEach(cleanup);

function setup(query = "") {
  return render(<><ProblemPage /><LocationProbe /></>, {
    wrapper: createRouterWrapper(`/problems?useFilterStorage=false&${query}`),
  });
}

function rowIds() {
  return within(screen.getByRole("table")).getAllByRole("row").slice(1)
    .map((row) => within(row).getAllByRole("cell")[1].textContent);
}

async function openFilters() {
  // The current filter trigger is icon-only; scope its lookup to the toolbar.
  fireEvent.click(screen.getByPlaceholderText("Problem Name or Id").closest("ul")!.querySelector("li:last-child button")!);
  return screen.findByRole("dialog");
}

// Generated by Codex and not thoroughly checked for correctness.
test("searching on a late page resets the page and clearing search restores results", () => {
  setup("perPage=2&page=2");
  expect(rowIds()).toEqual(["15000A"]);
  fireEvent.change(screen.getByPlaceholderText("Problem Name or Id"), { target: { value: " ALPHA " } });
  expect(rowIds()).toEqual(["100A"]);
  expect(screen.getByText("Page 1 of 1")).toBeDefined();
  fireEvent.change(screen.getByPlaceholderText("Problem Name or Id"), { target: { value: "" } });
  expect(rowIds()).toEqual(["100A", "100B"]);
});

// Generated by Codex and not thoroughly checked for correctness.
test("rating sliders and unrated toggle update visible table rows", async () => {
  setup();
  const dialog = await openFilters();
  fireEvent.change(within(dialog).getByRole("slider", { name: "Minimum rating" }), { target: { value: "1200" } });
  fireEvent.change(within(dialog).getByRole("slider", { name: "Maximum rating" }), { target: { value: "1600" } });
  fireEvent.click(within(dialog).getByRole("checkbox"));
  fireEvent.click(within(dialog).getByRole("button", { name: "Close" }));
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
  expect(rowIds()).toEqual(["100B", "101A"]);
});

