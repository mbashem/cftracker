test("an acceptance expanded from a shared contest marks its equivalent row solved with its own URL", () => {
  // The submission-store boundary supplies already-expanded shared submissions.
  const shared = createSubmission(2, frontend.problems[2], Verdict.OK, 200);
  shared.fromShared = true;
  frontend.submissions.push(shared);
  setup("status=SOLVED");
  expect(rowIds()).toEqual(["100A", "101A"]);
  const equivalent = screen.getByRole("link", { name: "Gamma Mixed" });
  expect(equivalent.getAttribute("href")).toBe("https://codeforces.com/contest/101/problem/A");
  expect(equivalent.closest("td")!.classList.contains(frontend.theme!.bgSuccess)).toBe(true);
});
