import { frontend, resetFrontendMocks } from "../support/frontendMocks";
import { act, cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import SubmissionsHeatMap from "../../src/components/stats/charts/SubmissionsHeatMap";
import { Verdict } from "../../src/types/CF/Submission";
import { StorageService } from "../../src/util/StorageService";
import Theme, { ThemesType } from "../../src/util/Theme";
import { createSubmission, seedProblemFixtures } from "../support/problemFixtures";

beforeEach(() => {
  resetFrontendMocks();
  localStorage.clear();
  seedProblemFixtures();
  const dates = [new Date(2025, 0, 1, 0, 1), new Date(2024, 1, 29, 23, 59), new Date(2023, 11, 31, 23, 59), new Date(2024, 0, 1, 0, 1), new Date(2024, 1, 29, 0, 1)];
  // Deliberately unordered, with two submissions on local leap day.
  frontend.submissions = dates.map((date, index) => createSubmission(index + 1, frontend.problems[0], Verdict.WRONG_ANSWER, date.getTime() / 1000));
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); });

function cells(svg: SVGSVGElement) { return svg.querySelectorAll("rect"); }
function select(value: string) {
  fireEvent.change(screen.getByRole("combobox", { name: "Select heatmap year" }), { target: { value } });
}

// Generated by Codex and not thoroughly checked for correctness.
test("All groups local year boundaries and leap day without reordering source submissions", () => {
  const ids = frontend.submissions.map((submission) => submission.id);
  const view = render(<SubmissionsHeatMap />);
  select("all");
  const svgs = view.container.querySelectorAll("svg");
  expect(svgs).toHaveLength(3);
  expect(cells(svgs[0])).toHaveLength(365);
  expect(cells(svgs[1])).toHaveLength(366);
  expect(cells(svgs[2])).toHaveLength(365);
  fireEvent.mouseEnter(cells(svgs[0])[364]);
  expect(screen.getByText("Sun Dec 31 2023: 1")).toBeDefined();
  fireEvent.mouseEnter(cells(svgs[1])[0]);
  expect(screen.getByText("Mon Jan 01 2024: 1")).toBeDefined();
  fireEvent.mouseEnter(cells(svgs[1])[59]);
  expect(screen.getByText("Thu Feb 29 2024: 2")).toBeDefined();
  fireEvent.mouseEnter(cells(svgs[2])[0]);
  expect(screen.getByText("Wed Jan 01 2025: 1")).toBeDefined();
  expect(frontend.submissions.map((submission) => submission.id)).toEqual(ids);
});

