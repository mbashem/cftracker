test("heatmap responds to resize and theme changes with counts unchanged", () => {
  const originalWidth = window.innerWidth;
  const view = render(<SubmissionsHeatMap />);
  const resize = (width: number) => {
    Object.defineProperty(window, "innerWidth", { configurable: true, value: width });
    act(() => { window.dispatchEvent(new Event("resize")); });
  };
  try {
    resize(1440);
    expect(cells(view.container.querySelector("svg")!)[0].getAttribute("width")).toBe("13");
    resize(375);
    expect(cells(view.container.querySelector("svg")!)[0].getAttribute("width")).toBe("5");
    frontend.theme = new Theme(ThemesType.DARK);
    select("2024");
    expect(view.container.querySelector("svg text")!.classList.contains("text-light")).toBe(true);
    fireEvent.mouseEnter(cells(view.container.querySelector("svg")!)[59]);
    expect(screen.getByText("Thu Feb 29 2024: 2")).toBeDefined();
  } finally { resize(originalWidth); }
});
