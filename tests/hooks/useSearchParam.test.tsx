// Generated by Codex and not thoroughly checked for correctness.
test("consuming temporary keys preserves unrelated URL state and replaces history", () => {
  const hook = setup();
  act(() => { void hook.result.current.navigate("/problems?random=true&listId=5&q=keep"); });
  act(() => hook.result.current.params.consumeSearchParams([SearchKeys.Random, SearchKeys.ListId]));
  expect(hook.result.current.params.getSearchParam(SearchKeys.Random)).toBeUndefined();
  expect(hook.result.current.params.getSearchParam(SearchKeys.ListId)).toBeUndefined();
  expect(hook.result.current.params.getSearchParam(SearchKeys.Search)).toBe("keep");
  act(() => { void hook.result.current.navigate(-1); });
  expect(hook.result.current.params.getSearchParam(SearchKeys.Search)).toBe("old");
});

