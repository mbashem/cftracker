test("navigation preserves explicit zero/false/text and omits absent values", () => {
  const hook = setup();
  act(() => hook.result.current.app.navigateTo(Path.CONTESTS, { [SearchKeys.Page]: 0, [SearchKeys.Random]: false, [SearchKeys.Search]: "dp & +", [SearchKeys.ListId]: undefined }));
  const params = new URLSearchParams(hook.result.current.location.search);
  expect(hook.result.current.app.pathName).toBe(Path.CONTESTS);
  expect(params.get(SearchKeys.Page)).toBe("0");
  expect(params.get(SearchKeys.Random)).toBe("false");
  expect(params.get(SearchKeys.Search)).toBe("dp & +");
  expect(params.has(SearchKeys.ListId)).toBe(false);
  expect(params.has("keep")).toBe(false);
});

