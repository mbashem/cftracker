// Generated by Codex and not thoroughly checked for correctness.
test("logout in another hook instance prevents a pending callback from restoring identity", async () => {
  let resolve!: (value: Response) => void;
  backend.fetchMock.mockImplementationOnce(() => new Promise(done => { resolve = done; }));
  const callback = renderHook(useUser, { wrapper: backend.wrapper });
  const menu = renderHook(useUser, { wrapper: backend.wrapper });
  let pending!: Promise<void>;
  act(() => { pending = callback.result.current.handleGithubCallback("pending", "state"); });
  await vi.waitFor(() => expect(backend.fetchMock).toHaveBeenCalledTimes(1));
  act(() => menu.result.current.logout());
  await act(async () => { resolve(Response.json({ user: backendUser, token: "late-session" })); await pending; });
  expect(callback.result.current.isAuthenticated).toBe(false);
  expect(StorageService.getJWTToken()).toBeNull();
});

// Generated by Codex and not thoroughly checked for correctness.
test("a superseded authentication response cannot replace the latest identity", async () => {
  let resolveOld!: (value: Response) => void;
  backend.fetchMock.mockImplementationOnce(() => new Promise(done => { resolveOld = done; })).mockResolvedValueOnce(Response.json({ user: { ...backendUser, github_username: "latest" }, token: "latest-session" }));
  const hook = renderHook(useUser, { wrapper: backend.wrapper });
  let old!: Promise<void>;
  act(() => { old = hook.result.current.handleGithubCallback("old", "state"); });
  await vi.waitFor(() => expect(backend.fetchMock).toHaveBeenCalledTimes(1));
  await act(async () => { await hook.result.current.handleGithubCallback("new", "state"); });
  await act(async () => { resolveOld(Response.json({ user: backendUser, token: "old-session" })); await old; });
  expect(hook.result.current.user?.githubUsername).toBe("latest");
  expect(StorageService.getJWTToken()).toBe("latest-session");
});
