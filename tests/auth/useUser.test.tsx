test.each([[401, { error: "Invalid state" }, "Invalid state"], [403, {}, "Authentication failed!"], [500, {}, "Authentication failed!"]])(
  "callback HTTP %i rejection leaves the user anonymous and records feedback", async (status, body, message) => {
    backend.respond(body, status as number);
    const hook = renderHook(useUser, { wrapper: backend.wrapper });
    await act(async () => { await expect(hook.result.current.handleGithubCallback("bad", "state")).rejects.toThrow(message as string); });
    expect(hook.result.current.isAuthenticated).toBe(false);
    expect(backend.store.getState().userList.error).toBe(message);
    expect(StorageService.getJWTToken()).toBeNull();
  },
);

