test("logout clears Redux identity and stops sending authorization on subsequent requests", async () => {
  backend.respond({ user: backendUser, token: "test-session" });
  const hook = renderHook(useUser, { wrapper: backend.wrapper });
  await act(async () => hook.result.current.handleGithubCallback("code", "state"));
  backend.respond({ lists: [] });
  await act(async () => { await backend.store.dispatch(listApi.endpoints.getAllLists.initiate()).unwrap(); });
  expect(backend.requests[backend.requests.length - 1]?.headers.get("Authorization")).toBe("Bearer test-session");
  act(() => hook.result.current.logout());
  expect(hook.result.current.user).toBeUndefined();
  expect(hook.result.current.isAuthenticated).toBe(false);
  expect(StorageService.getJWTToken()).toBeNull();
  await act(async () => { await backend.store.dispatch(listApi.endpoints.getAllLists.initiate(undefined, { forceRefetch: true })).unwrap(); });
  expect(backend.requests[backend.requests.length - 1]?.headers.has("Authorization")).toBe(false);
});

