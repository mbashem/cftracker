import { backendUser, listApi, setupBackendMock } from "../support/backendMocks";
import { act, cleanup, renderHook } from "@testing-library/react";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import useUser from "../../src/hooks/useUser";
import { errorAuthenticatingUser } from "../../src/data/reducers/userSlice";
import { StorageService } from "../../src/util/StorageService";

let backend: ReturnType<typeof setupBackendMock>;
beforeEach(() => {
  localStorage.clear();
  backend = setupBackendMock();
  vi.spyOn(console, "log").mockImplementation(() => {});
});
afterEach(() => { cleanup(); backend.dispose(); localStorage.clear(); vi.restoreAllMocks(); });

// Generated by Codex and not thoroughly checked for correctness.
test("GitHub callback maps the user, clears the previous error and persists the token", async () => {
  backend.respond({ user: backendUser, token: "test-session" });
  backend.store.dispatch(errorAuthenticatingUser({ errorMessage: "Previous failure" }));
  const hook = renderHook(useUser, { wrapper: backend.wrapper });
  expect(hook.result.current.isAuthenticated).toBe(false);
  await act(async () => hook.result.current.handleGithubCallback("code +/?", "state &?"));
  expect(hook.result.current.user).toEqual({
    id: 7, githubId: 42, githubUsername: "octocat", email: "octocat@example.test",
    avatarUrl: "https://example.test/avatar", cfHandle: "tourist", cfVerified: true, admin: false, jwtToken: "test-session",
  });
  expect(hook.result.current.isAuthenticated).toBe(true);
  expect(backend.store.getState().userList.error).toBe("");
  expect(StorageService.getJWTToken()).toBe("test-session");
  const request = backend.requests[0];
  const url = new URL(request.url);
  expect(url.pathname).toBe("/auth/github/callback");
  expect(url.searchParams.get("code")).toBe("code +/?");
  expect(url.searchParams.get("state")).toBe("state &?");
  expect(request.method).toBe("GET");
  expect(request.credentials).toBe("include");
});

