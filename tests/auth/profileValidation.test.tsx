import { backendUser, setupBackendMock } from "../support/backendMocks";
import { act, cleanup, render, renderHook, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import { StrictMode, type PropsWithChildren } from "react";
import useAuthenticationBootstrap from "../../src/hooks/useAuthenticationBootstrap";
import useUser from "../../src/hooks/useUser";
import { removeUser } from "../../src/data/reducers/userSlice";
import { validateSession } from "../../src/data/actions/authentication";
import { StorageService } from "../../src/util/StorageService";
import { MemoryRouter } from "react-router";
import AuthGuard from "../../src/util/route/AuthGuard";
import { LocationProbe } from "../support/router";

let backend: ReturnType<typeof setupBackendMock>;
beforeEach(() => {
  localStorage.clear(); backend = setupBackendMock();
  vi.spyOn(console, "log").mockImplementation(() => {});
});
afterEach(() => { cleanup(); backend.dispose(); localStorage.clear(); vi.restoreAllMocks(); });
function bootstrap() {
  return renderHook(() => { useAuthenticationBootstrap(); return useUser(); }, { wrapper: backend.wrapper });
}

// Generated by Codex and not thoroughly checked for correctness.
test("startup authenticates only after the profile request succeeds with the stored bearer token", async () => {
  StorageService.setJWTToken("saved-session");
  let resolve!: (value: Response) => void;
  backend.fetchMock.mockImplementationOnce(() => new Promise(done => { resolve = done; }));
  const hook = bootstrap();
  expect(hook.result.current.isAuthenticated).toBe(false);
  expect(hook.result.current.isCheckingAuthentication).toBe(true);
  await waitFor(() => expect(backend.fetchMock).toHaveBeenCalledTimes(1));
  const request = new Request(backend.fetchMock.mock.calls[0][0]);
  expect(new URL(request.url).pathname).toBe("/api/v1/user/profile");
  expect(request.headers.get("Authorization")).toBe("Bearer saved-session");
  await act(async () => { resolve(Response.json({ user: backendUser })); });
  await waitFor(() => expect(hook.result.current.isAuthenticated).toBe(true));
  expect(hook.result.current.user?.githubUsername).toBe("octocat");
});

// Generated by Codex and not thoroughly checked for correctness.
test.each([401, 403, 500])("a failed profile request (HTTP %i) clears the session instead of trusting saved identity", async status => {
  StorageService.setJWTToken("saved-session");
  backend.respond({ error: "Profile unavailable" }, status);
  const hook = bootstrap();
  await waitFor(() => expect(hook.result.current.isCheckingAuthentication).toBe(false));
  expect(hook.result.current.isAuthenticated).toBe(false);
  expect(hook.result.current.user).toBeUndefined();
  expect(StorageService.getJWTToken()).toBeNull();
  expect(backend.store.getState().listApi.queries).toEqual({});
});

