test("revalidating a session refetches the profile instead of accepting its cached success", async () => {
  backend.respond({ user: backendUser });
  await backend.store.dispatch(validateSession("session"));
  expect(backend.store.getState().userList.authenticationStatus).toBe("authenticated");
  backend.respond({ error: "Unauthorized" }, 401);
  await backend.store.dispatch(validateSession("session"));
  expect(backend.requests).toHaveLength(2);
  expect(backend.store.getState().userList.authenticationStatus).toBe("unauthenticated");
});

