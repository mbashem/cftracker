// Generated by Codex and not thoroughly checked for correctness.
test("a profile failure from a superseded session cannot log out the latest validated session", async () => {
  StorageService.setJWTToken("old-session");
  let resolveOld!: (value: Response) => void;
  backend.fetchMock.mockImplementationOnce(() => new Promise(done => { resolveOld = done; }));
  const hook = bootstrap();
  await waitFor(() => expect(backend.fetchMock).toHaveBeenCalledTimes(1));
  backend.respond({ user: { ...backendUser, id: 8, github_username: "latest" } });
  await act(async () => { await backend.store.dispatch(validateSession("new-session")); });
  await act(async () => { resolveOld(Response.json({ error: "Unauthorized" }, { status: 401 })); });
  expect(hook.result.current.user?.githubUsername).toBe("latest");
  expect(hook.result.current.isAuthenticated).toBe(true);
  expect(StorageService.getJWTToken()).toBe("new-session");
});

