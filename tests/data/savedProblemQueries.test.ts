  backend.respond({ status: "FAILED" });
  await expect(backend.store.dispatch(catalogApi.endpoints.getProblems.initiate()).unwrap()).rejects.toMatchObject({
    status: "CUSTOM_ERROR", error: "Failed to load saved Problems list.",
  });
