test("real handle operations trim and deduplicate input, remove handles and clear all", () => {
  const hook = renderHook(useUserStore, { wrapper: backend.wrapper });
  act(() => hook.result.current.updateUsers(" tourist,jiangly,tourist, , "));
  expect(hook.result.current.userList.handles).toEqual(["tourist", "jiangly"]);
  act(() => hook.result.current.removeHandle("tourist"));
  expect(hook.result.current.userList.handles).toEqual(["jiangly"]);
  act(() => hook.result.current.addHandle(" jiangly "));
  expect(hook.result.current.userList.handles).toEqual(["jiangly"]);
  act(() => hook.result.current.updateUsers(" , "));
  expect(hook.result.current.userList.handles).toEqual([]);
});

