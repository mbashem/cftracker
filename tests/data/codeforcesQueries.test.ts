test.each([
  ["getContest", "Failed to load saved contestList."],
  ["getSharedProblems", "Error processing shared problems"],
] as const)("%s rejects failed JSON payloads with the existing error", async (endpoint, message) => {
  backend.respond({ status: "FAILED" });
  await expect(requestSavedCatalog(endpoint).unwrap()).rejects.toMatchObject({ status: "CUSTOM_ERROR", error: message });
});
