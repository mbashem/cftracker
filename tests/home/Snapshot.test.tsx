// Generated by Codex and not thoroughly checked for correctness.
test.each([
  [SnapshotPeriod.WEEK, new Date(2026, 9, 24), "24/10/2026 to 30/10/2026"],
  [SnapshotPeriod.MONTH, new Date(2026, 9, 1), "01/10/2026 to 30/10/2026"],
  [SnapshotPeriod.YEAR, new Date(2025, 9, 31), "31/10/2025 to 30/10/2026"],
])("%s Snapshot displays its actual inclusive date range", (period, start, label) => {
  render(<MemoryRouter><Snapshot
    submissions={[]}
    statistics={{ solvedCount: 0, activeDays: 0, averageSolvedRating: undefined, attemptedUnsolvedCount: 0, solvedProblems: [], attemptedUnsolvedProblems: [] }}
    statisticDetails={{}}
    period={period}
    range={{ startTimeSeconds: start.getTime() / 1000, endTimeSeconds: new Date(2026, 9, 31).getTime() / 1000 }}
    customRange={{}}
    hasHandles hasSubmissions={false} hasError={false} isLoading={false}
    onPeriodChange={vi.fn()} onCustomRangeChange={vi.fn()}
  /></MemoryRouter>);
  expect(screen.getByText(label)).toBeDefined();
  const grouping = { Week: "Daily", Month: "Weekly", Year: "Monthly" }[period];
  expect(screen.getByRole("group", { name: `${grouping} submission activity for the selected range` })).toBeDefined();
});

// Generated by Codex and not thoroughly checked for correctness.
test("active days link includes solved and attempted submissions", () => {
  render(
    <MemoryRouter>
      <Snapshot
        submissions={[]}
        statistics={{
          solvedCount: 1,
          activeDays: 2,
          averageSolvedRating: undefined,
          attemptedUnsolvedCount: 1,
          solvedProblems: [],
          attemptedUnsolvedProblems: [],
        }}
        statisticDetails={{
          solvedContestRange: { min: 100, max: 150 },
          submittedContestRange: { min: 90, max: 200 },
          attemptedContestRange: { min: 90, max: 200 },
        }}
        period={SnapshotPeriod.WEEK}
        range={{ startTimeSeconds: 1_000, endTimeSeconds: 2_000 }}
        customRange={{}}
        hasHandles
        hasSubmissions
        hasError={false}
        isLoading={false}
        onPeriodChange={vi.fn()}
        onCustomRangeChange={vi.fn()}
      />
      <LocationProbe />
    </MemoryRouter>,
  );

  fireEvent.click(screen.getByRole("button", { name: /Active days/i }));

  const location = screen.getByTestId("location").textContent ?? "";
  const [path, search] = location.split("?");
  const params = new URLSearchParams(search);
  expect(path).toBe(Path.PROBLEMS);
  expect(params.get(SearchKeys.Status)).toBe(`${Verdict.SOLVED},${Verdict.ATTEMPTED}`);
  expect(params.get(SearchKeys.SubmittedAfter)).toBe("1000");
  expect(params.get(SearchKeys.SubmittedBefore)).toBe("2000");
  expect(params.get(SearchKeys.MinContestId)).toBe("90");
  expect(params.get(SearchKeys.MaxContestId)).toBe("200");
  expect(params.get(SearchKeys.UseFilterStorage)).toBe("false");
});
